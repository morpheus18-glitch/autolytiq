function applyUpdates(
  groups: Record<ComplianceGroupKey, ComplianceItem[]>,
  updates?: ComplianceUpdatePayload['updates'],
  completeAll?: boolean,
) {
  if (completeAll) {
    const timestamp = nowIso();
    (Object.keys(groups) as ComplianceGroupKey[]).forEach((groupKey) => {
      groups[groupKey] = groups[groupKey].map((item) => ({
        ...item,
        completed: item.required ? true : item.completed,
        completedAt: item.required ? timestamp : item.completedAt,
      }));
    });
    return groups;
  }

  if (!updates || updates.length === 0) {
    return groups;
  }

  for (const update of updates) {
    const groupItems = groups[update.group];
    const index = groupItems.findIndex((item) => item.id === update.itemId);
    if (index === -1) {
      continue;
    }
    const completed = Boolean(update.completed);
    groupItems[index] = {
      ...groupItems[index],
      completed,
      completedAt: completed ? nowIso() : null,
      documentUrl: update.documentUrl ?? groupItems[index].documentUrl,
      notes: update.notes ?? groupItems[index].notes,
    };
  }

  return groups;
}

async function createPdf(render: (doc: InstanceType<typeof PDFDocument>) => void) {
  const doc = new PDFDocument({ size: 'LETTER', margin: 36 });
  const chunks: Buffer[] = [];

  doc.on('data', (chunk) => chunks.push(chunk as Buffer));

  return await new Promise<Buffer>((resolve, reject) => {
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', (error) => reject(error));
    render(doc);
    doc.end();
  });
}


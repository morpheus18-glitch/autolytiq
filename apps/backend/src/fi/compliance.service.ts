function resolveStateRegistry(state: string) {
  const normalized = state.toUpperCase();
  return STATE_REQUIREMENTS[normalized] ?? DEFAULT_STATE_REQUIREMENTS;
}

function buildVehicleDescription(deal: DealWithRelations) {
  const { vehicle } = deal;
  const parts = [vehicle?.year, vehicle?.make, vehicle?.model].filter(Boolean);
  return parts.length > 0 ? parts.join(' ') : 'Vehicle TBD';
}

function deriveStateFromDeal(deal: DealWithRelations) {
  const customer = deal.customer as DealWithRelations['customer'] & {
    addressState?: string | null;
    licenseState?: string | null;
  };
  const state = customer?.addressState || customer?.licenseState;
  return state ? state.toUpperCase() : 'GENERAL';
}

function decimalToNumber(value: Prisma.Decimal | string | number | null | undefined): number | null {
  if (value === null || value === undefined) {
    return null;
  }
  if (value instanceof Prisma.Decimal) {
    return Number(value.toString());
  }
  const numeric = typeof value === 'number' ? value : Number(value);
  return Number.isFinite(numeric) ? numeric : null;
}

function formatCurrency(value: Prisma.Decimal | string | number | null | undefined) {
  const numeric = decimalToNumber(value);
  if (numeric === null) {
    return '—';
  }
  return new Intl.NumberFormat('en-US', { style: 'currency', currency: 'USD' }).format(numeric);
}


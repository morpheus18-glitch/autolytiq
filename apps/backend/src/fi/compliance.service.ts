async function renderDocumentBuffer(type: ComplianceDocumentType, deal: DealWithRelations) {
  switch (type) {
    case 'buyers-guide':
      return renderBuyersGuide(deal);
    case 'tila':
      return renderTilaDisclosure(deal);
    default:
      throw new DocumentGenerationError(`Unsupported compliance document type: ${type}`);
  }
}

function updateGeneratedItem(
  groups: Record<ComplianceGroupKey, ComplianceItem[]>,
  type: ComplianceDocumentType,
  documentUrl: string,
) {
  const mapping = DOCUMENT_ITEM_MAP[type];
  const items = groups[mapping.group];
  const index = items.findIndex((item) => item.id === mapping.itemId);
  if (index === -1) {
    return;
  }
  items[index] = {
    ...items[index],
    completed: true,
    completedAt: nowIso(),
    documentUrl,
    autoGenerated: true,
  };
}

